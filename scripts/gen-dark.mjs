// push 78 · builds src/theme-dark.css from src/styles.css: every colour in the app, re-mapped for the Dark theme,
// scoped under html[data-theme="dark"]. Runs before every build (npm "prebuild"), so new screens get dark colours too.
import fs from 'node:fs';
import postcss from 'postcss';

const SRC = new URL('../src/styles.css', import.meta.url);
const OUT = new URL('../src/theme-dark.css', import.meta.url);
const P = { bg: '#121110', card: '#1E1C1A', ink: '#F1ECE4', muted: '#A39A8E', line: '#2E2A26', gold: '#D9B25E', ok: '#5CC08E', red: '#E07A7F' };

const hex = (h) => { h = h.slice(1); if (h.length === 3 || h.length === 4) h = [...h].map((c) => c + c).join(''); return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255).concat(h.length === 8 ? [parseInt(h.slice(6, 8), 16) / 255] : []); };
const toHsl = ([r, g, b]) => { const mx = Math.max(r, g, b), mn = Math.min(r, g, b), l = (mx + mn) / 2; if (mx === mn) return [0, 0, l]; const d = mx - mn; const s = l > 0.5 ? d / (2 - mx - mn) : d / (mx + mn);
  const h = mx === r ? (g - b) / d + (g < b ? 6 : 0) : mx === g ? (b - r) / d + 2 : (r - g) / d + 4; return [h / 6, s, l]; };
const fromHsl = ([h, s, l]) => { if (!s) return [l, l, l]; const q = l < 0.5 ? l * (1 + s) : l + s - l * s, p = 2 * l - q;
  const f = (t) => { t = (t + 1) % 1; return t < 1 / 6 ? p + (q - p) * 6 * t : t < 1 / 2 ? q : t < 2 / 3 ? p + (q - p) * (2 / 3 - t) * 6 : p; }; return [f(h + 1 / 3), f(h), f(h - 1 / 3)]; };
const out = (rgb, a = 1) => { const c = rgb.map((x) => Math.round(Math.max(0, Math.min(1, x)) * 255)); return a < 1 ? `rgba(${c.join(',')},${+a.toFixed(3)})` : '#' + c.map((x) => x.toString(16).padStart(2, '0')).join('').toUpperCase(); };

/** kind: 'fg' (text), 'bg' (fills), 'line' (borders), 'shadow' */
const CHAR = [0x2A / 255, 0x26 / 255, 0x22 / 255];
function map(rgb, a, kind, keepWhite, btn = false) {
  const [h, s, l] = toHsl(rgb);
  if (kind === 'fg' && l > 0.9 && s < 0.3 && keepWhite !== 'dark') return out(hex('#F1ECE4').slice(0, 3), a);   // white text on dark cards stays light
  if (kind === 'fg' && l > 0.9 && keepWhite === 'dark') return out(hex('#1A1714').slice(0, 3), a);
  if (kind === 'bg' && !btn && (s < 0.22 || l < 0.08) && l < 0.25) return out(CHAR, a);                       // dark cards / bars → charcoal
  if (kind === 'shadow' && a < 0.35 && l < 0.5) return out([0, 0, 0], Math.min(0.6, a * 2.5));
  if (keepWhite && l > 0.97) return out(rgb, a);
  const neutral = s < 0.22 || l > 0.96 || l < 0.04;
  if (neutral) {
    let L;
    if (l >= 0.995) L = kind === 'fg' ? 0.08 : kind === 'line' ? 0.17 : 0.112;          // white: card (#1E1C1A) · dark text on light buttons
    else if (l >= 0.85) L = kind === 'line' ? 0.2 : 0.112 + ((0.995 - l) / 0.145) * 0.09;  // page tints → just above card
    else L = 0.95 - l * 0.88;                                                             // text / dark fills → light
    return out(fromHsl([30 / 360, 0.08, L]), a);
  }
  if (kind === 'fg') return out(fromHsl([h, Math.min(1, s * 0.85), Math.max(l, 0.66)]), a);
  if (l > 0.8) return out(fromHsl([h, s * 0.45, kind === 'line' ? 0.26 : 0.17]), a);     // tinted backgrounds (gold, red, green chips)
  return out(fromHsl([h, s * 0.9, Math.max(l, 0.36)]), a);                                 // strong fills keep their colour
}

const COLOR = /#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3,4}\b|rgba?\([^)]*\)|\bwhite\b|\bblack\b/g;
function swap(value, kind, keepWhite, btn) {
  return value.replace(COLOR, (m) => {
    let rgb, a = 1;
    if (m === 'white') rgb = [1, 1, 1]; else if (m === 'black') rgb = [0, 0, 0];
    else if (m[0] === '#') { const v = hex(m); rgb = v.slice(0, 3); a = v[3] ?? 1; }
    else { const n = m.match(/[\d.]+%?/g); if (!n || n.length < 3) return m; rgb = n.slice(0, 3).map((x) => (x.endsWith('%') ? parseFloat(x) / 100 : +x / 255)); a = n[3] != null ? +n[3] : 1; }
    return map(rgb, a, kind, keepWhite, btn);
  });
}
const kindOf = (prop) => /^(color|fill|stroke|caret-color|text-decoration-color|-webkit-text-fill-color)$/.test(prop) ? 'fg'
  : /shadow/.test(prop) ? 'shadow' : /border|outline/.test(prop) ? 'line' : 'bg';

const ROOT_VARS = { '--soft': '#8A8177', '--sand': '#2A2622', '--gold': P.gold, '--ink': P.ink, '--muted': P.muted, '--line': P.line, '--bg': P.bg, '--card': P.card, '--accent': P.red, '--accent-bg': '#3A1E20', '--ok': P.ok, '--ok-bg': '#173326' };
const root = postcss.parse(fs.readFileSync(SRC, 'utf8'));
const dark = postcss.root();
dark.append(postcss.comment({ text: ' generated by scripts/gen-dark.mjs · do not edit ' }));
const scope = (sel) => sel.split(',').map((s) => { s = s.trim(); if (s === ':root' || s === 'html') return 'html[data-theme="dark"]'; if (s.startsWith('body')) return 'html[data-theme="dark"] ' + s; return 'html[data-theme="dark"] ' + s; }).join(', ');
root.walkRules((rule) => {
  if (rule.parent?.type === 'atrule' && /keyframes/i.test(rule.parent.name)) return;
  const btn = /btn|button|chip|pill|\.seg|toggle|\.on\b|primary|switch|tab-?on/i.test(rule.selector);
  const inkBg = rule.nodes.some((d) => d.type === 'decl' && /^background/.test(d.prop) && /var\(--ink\)/.test(d.value));
  const darkLit = rule.nodes.some((d) => d.type === 'decl' && /^background/.test(d.prop) && (d.value.match(COLOR) ?? []).some((c) => { if (!c.startsWith('#')) return false; const [, s, l] = toHsl(hex(c).slice(0, 3)); return s < 0.22 && l < 0.25; }));
  const decls = []; const satBg = rule.nodes.some((d) => d.type === 'decl' && /^background/.test(d.prop) && (d.value.match(COLOR) ?? []).some((c) => { if (!c.startsWith('#')) return false; const [, s, l] = toHsl(hex(c).slice(0, 3)); return s > 0.3 && l < 0.6; }));
  for (const d of rule.nodes) {
    if (d.type !== 'decl') continue;
    if (d.prop.startsWith('--')) { COLOR.lastIndex = 0;
      if (ROOT_VARS[d.prop]) decls.push(postcss.decl({ prop: d.prop, value: ROOT_VARS[d.prop] }));
      else if (COLOR.test(d.value)) { const k = /ink|text|soft|muted|dim|fg/.test(d.prop) || !/bg|sand|cream|night|card|sq|btn|line|border/.test(d.prop) ? 'fg' : /line|border/.test(d.prop) ? 'line' : 'bg'; COLOR.lastIndex = 0; decls.push(postcss.decl({ prop: d.prop, value: swap(d.value, k, k === 'fg' ? 'light' : false, false) })); }
      COLOR.lastIndex = 0; continue; }
    COLOR.lastIndex = 0; if (!COLOR.test(d.value)) continue; COLOR.lastIndex = 0;
    const k = kindOf(d.prop);
    const keep = k !== 'fg' ? false : satBg ? true : (inkBg && btn) || (darkLit && btn) ? 'dark' : 'light';
    const nv = swap(d.value, k, keep, btn);
    if (nv !== d.value) decls.push(postcss.decl({ prop: d.prop, value: nv, important: d.important }));
  }
  if (inkBg && !btn) decls.push(postcss.decl({ prop: 'background', value: '#2A2622' }));
  if (!decls.length) return;
  const r = postcss.rule({ selector: scope(rule.selector) }); r.append(decls);
  if (rule.parent?.type === 'atrule') { const at = postcss.atRule({ name: rule.parent.name, params: rule.parent.params }); at.append(r); dark.append(at); } else dark.append(r);
});
dark.append(postcss.parse(`html[data-theme="dark"] { color-scheme: dark; }
html[data-theme="dark"] body { background: ${P.bg}; color: ${P.ink}; }
html[data-theme="dark"] img.logo-ink, html[data-theme="dark"] .logo-ink { filter: invert(1) hue-rotate(180deg); }`));
fs.writeFileSync(OUT, dark.toString());
console.log('theme-dark.css', dark.nodes.length, 'rules');
